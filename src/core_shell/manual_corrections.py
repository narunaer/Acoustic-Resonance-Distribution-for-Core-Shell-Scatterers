def _manual_peaks_on_mesh(x_mesh, W, prominence_min):
    """Peak detector used by the original hand-insertion block."""
    x_mesh = np.asarray(x_mesh, dtype=float)
    W = np.asarray(W, dtype=float)
    ylog = prepare_log_signal(W)
    if ylog is None:
        return []

    indices, _ = find_peaks(ylog, prominence=float(prominence_min))
    indices = indices[(indices >= 3) & (indices <= len(x_mesh) - 4)]
    if len(indices) == 0:
        return []

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        _, _, left_ips, right_ips = peak_widths(W, indices, rel_height=0.5)

    axis = np.arange(len(x_mesh), dtype=float)
    x_left = np.interp(left_ips, axis, x_mesh)
    x_right = np.interp(right_ips, axis, x_mesh)

    peaks = []
    for k, index in enumerate(indices):
        x0 = float(x_mesh[index])
        fwhm = float(x_right[k] - x_left[k])
        wt_peak = float(W[index])
        if not np.isfinite(fwhm) or fwhm <= 0.0:
            continue
        if not np.isfinite(wt_peak) or wt_peak <= 0.0:
            continue
        peaks.append({
            "xM_peak": x0,
            "FWHM": fwhm,
            "Q": x0 / fwhm,
            "WT_peak": wt_peak,
        })
    return peaks


