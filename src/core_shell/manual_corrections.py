def _manual_output_directory(raw_checkpoint: str) -> str:
    raw_dir = os.path.dirname(os.path.abspath(raw_checkpoint))
    if os.path.basename(raw_dir).lower() == "raw":
        return os.path.join(os.path.dirname(raw_dir), "manual_corrected")
    return raw_dir


def corrected_checkpoint_path(raw_checkpoint: str) -> str:
    if not raw_checkpoint.lower().endswith(".npz"):
        raise ValueError("The raw checkpoint must be an .npz file.")
    output_dir = _manual_output_directory(raw_checkpoint)
    os.makedirs(output_dir, exist_ok=True)
    stem = os.path.basename(raw_checkpoint)[:-4]
    return os.path.join(output_dir, stem + "_corrigido_manual.npz")


